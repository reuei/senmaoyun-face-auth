    /**
     * 校验身份证号
     */
    public function verify(string $idCard): array
    {
        // 基本格式校验
        if (!preg_match('/^\d{17}[\dXx]$/', $idCard)) {
            return [
                'valid'   => false,
                'message' => '身份证号格式不正确，应为18位数字，最后一位可为X',
            ];
        }

        $idCard = strtoupper($idCard);

        // 校验行政区划代码
        $areaCode = substr($idCard, 0, 6);
        if (!isset(self::AREA_CODES[$areaCode])) {
            // 尝试匹配到市级（前4位+00）
            $cityCode = substr($areaCode, 0, 4) . '00';
            if (!isset(self::AREA_CODES[$cityCode])) {
                // 尝试匹配到省级（前2位+0000）
                $provinceCode = substr($areaCode, 0, 2) . '0000';
                if (!isset(self::AREA_CODES[$provinceCode])) {
                    return [
                        'valid'   => false,
                        'message' => '身份证号行政区划代码无效',
                    ];
                }
            }
        }

        // 校验出生日期
        $birthDate = substr($idCard, 6, 8);
        $year   = (int)substr($birthDate, 0, 4);
        $month  = (int)substr($birthDate, 4, 2);
        $day    = (int)substr($birthDate, 6, 2);

        if (!checkdate($month, $day, $year)) {
            return [
                'valid'   => false,
                'message' => '身份证号出生日期无效',
            ];
        }

        // 出生日期不能是未来
        $birthDateTime = strtotime($birthDate);
        if ($birthDateTime > time()) {
            return [
                'valid'   => false,
                'message' => '身份证号出生日期不能是未来',
            ];
        }

        // ISO 7064:1983 MOD 11-2 校验码算法
        $sum = 0;
        for ($i = 0; $i < 17; $i++) {
            $sum += (int)$idCard[$i] * self::WEIGHT_FACTORS[$i];
        }
        $mod = $sum % 11;
        $expectedCheckCode = self::CHECK_CODES[$mod];

        if ($idCard[17] !== $expectedCheckCode) {
            return [
                'valid'   => false,
                'message' => '身份证号校验码错误，请检查是否正确',
            ];
        }

        // 性别判定（第17位，奇数为男，偶数为女）
        $genderCode = (int)$idCard[16];
        $gender = ($genderCode % 2 === 1) ? 'male' : 'female';

        // 计算年龄
        $today = new \DateTime();
        $birth = new \DateTime($year . '-' . $month . '-' . $day);
        $age = $today->diff($birth)->y;

        return [
            'valid'      => true,
            'message'    => '身份证号校验通过',
            'area_code'  => $areaCode,
            'area_name'  => self::AREA_CODES[$areaCode] ?? self::AREA_CODES[$cityCode] ?? self::AREA_CODES[$provinceCode] ?? '未知地区',
            'birth_date' => $year . '-' . str_pad((string)$month, 2, '0', STR_PAD_LEFT) . '-' . str_pad((string)$day, 2, '0', STR_PAD_LEFT),
            'gender'     => $gender,
            'gender_text'=> $gender === 'male' ? '男' : '女',
            'age'        => $age,
        ];
    }
